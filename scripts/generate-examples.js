#!/usr/bin/env node

import { writeFile, mkdir, readdir, rm } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { compose } from "../builder/index.js";
import { presets, exampleNames, packageManagers } from "../builder/options.js";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const examplesDir = path.join(root, "examples");

// Installs, lockfiles and build output live inside an example but are not
// generated. Removing them would uninstall the example's dependencies out from
// under any dev server running against it.
const localArtifacts = new Set([
	"node_modules",
	"dist",
	".vite",
	".cache",
	".vercel",
	"package-lock.json",
	"npm-shrinkwrap.json",
	"pnpm-lock.yaml",
	"yarn.lock",
	"bun.lock",
	"bun.lockb"
]);

const pruneStale = async (dir, keep, prefix = "") => {
	let entries;
	try {
		entries = await readdir(dir, { withFileTypes: true });
	} catch {
		return;
	}

	for (const entry of entries) {
		if (prefix === "" && localArtifacts.has(entry.name)) continue;

		const target = path.join(dir, entry.name);
		if (entry.isDirectory()) {
			await pruneStale(target, keep, `${prefix}${entry.name}/`);
			if (!(await readdir(target)).length)
				await rm(target, { recursive: true });
		} else if (!keep.has(`${prefix}${entry.name}`)) {
			await rm(target);
		}
	}
};

for (const [preset, dirName] of Object.entries(exampleNames)) {
	const outDir = path.join(examplesDir, dirName);

	const { files, options, notes } = await compose({
		...presets[preset].options,
		name: dirName
	});

	await pruneStale(outDir, new Set(Object.keys(files)));

	for (const [relative, contents] of Object.entries(files)) {
		const target = path.join(outDir, relative);
		await mkdir(path.dirname(target), { recursive: true });
		await writeFile(target, contents);
	}

	console.log(
		`${dirName.padEnd(20)} ${Object.keys(files).length} files · ${options.engine} · ${options.wiring} · ${
			options.features.join(", ") || "no extra features"
		}`
	);
	for (const note of notes) console.log(`  note: ${note}`);
}

const readme = `# Examples

Pre-generated output from the builder presets. **Do not edit these by hand** —
they are regenerated by \`npm run examples\` and any changes will be lost.

Each is a complete, standalone project:

\`\`\`bash
cd examples/barebones
npm install
npm start
\`\`\`

| Directory | Preset | Package manager | What it is |
|---|---|---|---|
${Object.entries(exampleNames)
	.map(([preset, dir]) => {
		const manager = presets[preset].options.packageManager;
		return `| [\`${dir}/\`](${dir}/) | \`${preset}\` | ${packageManagers[manager].label} | ${presets[preset].description} |`;
	})
	.join("\n")}

To produce your own combination:

\`\`\`bash
node builder/cli.js --out ./my-proxy --features tabs,settings,history
\`\`\`

Or run the documentation site and open its \`/build\` route.
`;

await writeFile(path.join(examplesDir, "README.md"), readme);
console.log("\nWrote examples/README.md");
